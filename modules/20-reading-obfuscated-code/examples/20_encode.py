#!/usr/bin/env python3
"""Module 20 example: writes 20_blobs.h, the encoded strings used by 20_strings.c.

Two schemes: a single-byte xor with a fixed key, and a rolling key where each byte uses the
next value of k = (k * 5 + 3) mod 256, starting from a seed.
"""
PLAIN_A = b"https://config.example.test/a"
PLAIN_B = b"C:\\Temp\\out.dat"
KEY_A = 0x5A
SEED_B = 0x21


def xor_fixed(data: bytes, key: int) -> bytes:
    return bytes(b ^ key for b in data)


def xor_roll(data: bytes, seed: int) -> bytes:
    out, k = bytearray(), seed
    for b in data:
        k = (k * 5 + 3) & 0xFF
        out.append(b ^ k)
    return bytes(out)


def array(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const unsigned char {name}[{len(data)}] = {{{body}}};\n"


with open("20_blobs.h", "w") as f:
    f.write("/* Generated by 20_encode.py. */\n")
    f.write(array("BLOB_A", xor_fixed(PLAIN_A, KEY_A)))
    f.write(array("BLOB_B", xor_roll(PLAIN_B, SEED_B)))
    f.write(f"#define KEY_A 0x{KEY_A:02x}\n#define SEED_B 0x{SEED_B:02x}\n")
