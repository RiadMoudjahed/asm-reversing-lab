#!/usr/bin/env python3
"""Report missing and stale translations and regenerate i18n/status.md.

A learner-facing English page X.md must have X.ar.md, X.de.md, X.es.md and X.fr.md.
Each translation starts with:  <!-- source: X.md @ sha256:<12 hex> -->

Usage: python3 tools/i18n_check.py [--strict] [--no-write] [--stamp-new]
  --strict      exit 1 on any missing or stale file (used at release)
  --no-write    do not rewrite i18n/status.md
  --stamp-new   replace the SOURCEHASH placeholder that tools/translate_blocks.py writes with
                the current hash of the English file. It never touches an existing hash, so it
                cannot mark a stale translation as current.
Default exit status is 0 so development can proceed; findings are always printed.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANGS = ["ar", "de", "es", "fr"]
SKIP_DIRS = {".git", ".claude", "node_modules", "build", "start"}
# English-only maintainer documents.
ENGLISH_ONLY = {"PLAN.md", "CLAUDE.md", "CODE_OF_CONDUCT.md", "SKILL.md", "STYLE.md", "REVIEWING.md",
                "status.md", "PULL_REQUEST_TEMPLATE.md", "RELEASING.md"}
SRC_RE = re.compile(r"<!--\s*source:\s*(\S+)\s*@\s*sha256:([0-9a-f]{12})\s*-->")


def sha12(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def english_pages():
    for p in sorted(ROOT.rglob("*.md")):
        if set(p.relative_to(ROOT).parts) & SKIP_DIRS:
            continue
        if p.name in ENGLISH_ONLY or p.parts[-3:-1] == (".github", "ISSUE_TEMPLATE"):
            continue
        if re.search(r"\.(ar|de|es|fr)\.md$", p.name):
            continue
        yield p


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--strict", action="store_true")
    ap.add_argument("--no-write", action="store_true")
    ap.add_argument("--stamp-new", action="store_true")
    args = ap.parse_args()

    if args.stamp_new:
        stamped = 0
        for en in english_pages():
            for lang in LANGS:
                tr = en.with_name(en.stem + f".{lang}.md")
                if tr.exists() and "sha256:SOURCEHASH" in tr.read_text(encoding="utf-8")[:600]:
                    text = tr.read_text(encoding="utf-8")
                    tr.write_text(text.replace("sha256:SOURCEHASH", f"sha256:{sha12(en)}", 1), encoding="utf-8")
                    stamped += 1
        print(f"i18n: stamped {stamped} new translations")

    rows, missing, stale = [], 0, 0
    for en in english_pages():
        rel = en.relative_to(ROOT).as_posix()
        cur = sha12(en)
        cells = []
        for lang in LANGS:
            tr = en.with_name(en.stem + f".{lang}.md")
            if not tr.exists():
                cells.append("missing")
                missing += 1
                continue
            head = tr.read_text(encoding="utf-8")[:600]
            m = SRC_RE.search(head)
            if not m or m.group(2) != cur:
                cells.append("stale")
                stale += 1
            else:
                cells.append("current")
        rows.append((rel, cells))

    for rel, cells in rows:
        bad = [f"{l}:{c}" for l, c in zip(LANGS, cells) if not c.startswith("current")]
        if bad:
            print(f"{rel}: " + ", ".join(bad))
    print(f"i18n: {len(rows)} pages, {missing} missing, {stale} stale")

    if not args.no_write:
        out = ROOT / "i18n" / "status.md"
        lines = ["# Translation status", "",
                 "Generated by `tools/i18n_check.py`. Do not edit by hand.", "",
                 "| Page | " + " | ".join(LANGS) + " |",
                 "|---|" + "---|" * len(LANGS)]
        lines += [f"| {rel} | " + " | ".join(c) + " |" for rel, c in rows]
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    return 1 if args.strict and (missing or stale) else 0


if __name__ == "__main__":
    sys.exit(main())
