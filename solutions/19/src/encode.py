#!/usr/bin/env python3
"""Exercise 19: writes blobs.h (the encoded configuration of the simulator) and blobs_benign.h.

Record layout: length byte, seed byte, then the encoded bytes.
Decoding rule: k = seed; for each position i: k = ((k rotated left by 3) + i + 0x5d) mod 256;
the plain byte is the encoded byte xor k.
"""


def encode(text: str, seed: int) -> bytes:
    k, out = seed, bytearray()
    for i, ch in enumerate(text.encode()):
        k = (((k << 3) | (k >> 5)) & 0xFF)
        k = (k + i + 0x5D) & 0xFF
        out.append(ch ^ k)
    return bytes([len(text), seed]) + bytes(out)


def table(name: str, items) -> str:
    data = b"".join(encode(t, s) for t, s in items)
    body = ", ".join(f"0x{b:02x}" for b in data)
    return (f"static const unsigned char {name}[{len(data)}] = {{{body}}};\n"
            f"#define {name}_COUNT {len(items)}\n")


CONFIG = [
    ("WinUpdSvcHost", 0x13),
    ("C:\\ProgramData\\Intel\\svchost32.exe", 0xA7),
    ("version.dll", 0x5C),
    ("OneDriveUpdater.exe", 0x2E),
    ("ns1.cdn-telemetry.test", 0xD1),
    ("Security", 0x66),
]
BENIGN = [
    ("welcome to the notes tool", 0x41),
    ("notes.txt", 0x9B),
    ("C:\\Users\\Public\\Documents", 0x07),
]

with open("blobs.h", "w") as f:
    f.write("/* Generated by encode.py. */\n" + table("CONFIG", CONFIG))
with open("blobs_benign.h", "w") as f:
    f.write("/* Generated by encode.py. */\n" + table("TEXTS", BENIGN))
print(max(len(t) for t, _ in CONFIG), len(CONFIG))
